package com.mrboomdev.scrollix.data.api

import dev.g000sha256.tdl.TdlResult
import dev.g000sha256.tdl.dto.ChatNotificationSettings
import dev.g000sha256.tdl.dto.ForumTopicIcon
import kotlinx.coroutines.CancellationException

/**
 * Topic management for forum chats. Every failure becomes the shared
 * [com.mrboomdev.scrollix.data.model.SessionException], so the dialog can show
 * the server's own text instead of a generic message.
 */

/** Icon colour used for topics created from this client. */
private const val DefaultTopicColor = 0x6FB9F0

internal suspend fun TelegramSession.createForumTopicImpl(
    providerDialogId: String,
    title: String
): Result<Long> {
    val chatId = providerDialogId.toLongOrNull()
        ?: return Result.failure(IllegalArgumentException("Invalid dialog id"))

    val trimmed = title.trim()
    if (trimmed.isEmpty()) {
        return Result.failure(IllegalArgumentException("Topic title is empty"))
    }

    return try {
        when (val result = client.createForumTopic(
            chatId = chatId,
            name = trimmed,
            // The name is typed by the user, not generated by Telegram.
            isNameImplicit = false,
            icon = ForumTopicIcon(
                color = DefaultTopicColor,
                customEmojiId = 0L
            )
        )) {
            is TdlResult.Success -> Result.success(result.result.forumTopicId.toLong())
            is TdlResult.Failure -> Result.failure(result.toSessionException())
        }
    } catch (exception: CancellationException) {
        throw exception
    } catch (exception: Exception) {
        Result.failure(exception)
    }
}

